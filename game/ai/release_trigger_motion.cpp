  c->mem_w8(obj + 0x47, (uint8_t)(1 - c->mem_r8(obj + 0x47)));
  c->mem_w8(obj + 0x46, (uint8_t)(c->mem_r8(obj + 0x46) + 1));
  c->mem_w16(obj + 0x32, (uint16_t)(c->mem_r16s(obj + 0x32) - 8));
