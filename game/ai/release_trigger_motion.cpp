      int32_t idx = c->mem_r16s(obj + 0x60);
      int16_t tv = c->mem_r16s(TBL + (uint32_t)idx * 2);
      c->mem_w16(obj + 0x2e, (uint16_t)(c->mem_r16s(anchor + 0x2c) + tv));
